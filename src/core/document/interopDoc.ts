// The field reference of docs/INTEROP.md, generated from the field table (spec §21.4, Batch 54):
// `npm run docs:interop` writes it between the markers; a test fails when the file is stale. Pure.
import { FIELD_TABLE, type FieldType } from "./schema.js";

/** What the begin marker starts with (the rest of the line may change). */
export const FIELDS_BEGIN_START = "<!-- fields:begin";
export const FIELDS_BEGIN = "<!-- fields:begin (generated by `npm run docs:interop` from src/core/document/schema.ts; do not edit) -->";
export const FIELDS_END = "<!-- fields:end -->";

function typeLabel(type: FieldType): string {
  switch (type.t) {
    case "string":
      return type.nonEmpty ? "string (not empty)" : "string";
    case "boolean":
      return "boolean";
    case "number": {
      const base = type.integer ? "integer" : "number";
      const low = type.min !== undefined ? `${type.exclusiveMin ? ">" : ">="} ${type.min}` : "";
      const high = type.max !== undefined ? `<= ${type.max}` : "";
      const bounds = [low, high].filter(Boolean).join(", ");
      return bounds ? `${base} (${bounds})` : base;
    }
    case "enum":
      return type.values.map((value) => `\`${JSON.stringify(value)}\``).join(" \| ");
    case "object":
      return `[${type.schema}](#${anchor(type.schema)})${type.nullable ? " or null" : ""}`;
    case "array":
      return `${typeLabel(type.item)}[]${type.length !== undefined ? ` (${type.length} items)` : ""}`;
    case "record":
      return `object of ${typeLabel(type.item)}${type.keys ? ` (keys: ${type.keys.map((key) => `\`${key}\``).join(", ")})` : " by id"}`;
    case "union":
      return type.options.map((option) => typeLabel(option.type)).join(" \| ");
    case "json":
      return "object (opaque)";
    case "numberOrVector":
      return `number, or number[] (1 to ${type.max} items)`;
  }
}

const anchor = (name: string): string => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const cell = (value: string): string => value.replace(/\|/g, "\|").replace(/\n/g, " ");
const defaultLabel = (value: unknown): string => (value === undefined ? "" : `\`${cell(JSON.stringify(value))}\``);

/** The generated markdown, markers included. */
export function fieldReference(): string {
  const lines: string[] = [FIELDS_BEGIN, ""];
  for (const schema of Object.values(FIELD_TABLE)) {
    lines.push(`#### ${schema.name}`, "", schema.doc, "");
    if (schema.variants) {
      lines.push(`Told apart by \`kind\`: ${Object.entries(schema.variants).map(([kind, name]) => `\`${kind}\` is [${name}](#${anchor(name)})`).join(", ")}.`, "");
      continue;
    }
    if (schema.value) {
      lines.push(`Value: ${typeLabel(schema.value)}.`, "");
      continue;
    }
    lines.push("| Field | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |");
    for (const [key, field] of Object.entries(schema.fields)) {
      lines.push(`| \`${key}\` | ${typeLabel(field.type)} | ${field.required ? "yes" : "no"} | ${defaultLabel(field.default)} | ${cell(field.doc)} |`);
    }
    lines.push("");
  }
  lines.push(FIELDS_END);
  return lines.join("\n");
}
